import { chromium } from 'playwright';
import { startServer } from './server.mjs';
const { server, url } = await startServer('dist', 0);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'ko-KR' });
const page = await ctx.newPage();
page.on('crash', () => console.log('CRASH'));
page.on('pageerror', (e) => console.log('ERR', e.message));
await page.addInitScript(() => {
  localStorage.setItem('egg-gacha.pending.v1', JSON.stringify([{ uid: 'p1', egg: 'ice', ts: Date.now() }]));
});
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__eggGacha?.ready === true, null, { timeout: 20000 });
await page.click('#hatchCue');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/dev/h1-egg.png' });
await page.click('#hatchBtn', { noWaitAfter: true });
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/dev/h2-crack.png' });
await page.waitForSelector('#revealCard .dc', { timeout: 20000 });
await page.waitForTimeout(900);
await page.screenshot({ path: 'shots/dev/h3-reveal.png' });
console.log(JSON.stringify(await page.evaluate(() => { const s = window.__eggGacha.state(); return { dragons: s.dragons, pending: s.pending, first: s.dragonList[0] }; })).slice(0, 500));
await page.click('#revealClose');
await page.click('#dexBtn');
await page.waitForTimeout(300);
await page.click('#tabDragons');
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/dev/h4-gallery.png' });
await browser.close(); server.close();
