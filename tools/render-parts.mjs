/**
 * Renders every dragon part from tools/art/*.mjs into transparent PNGs,
 * then optimises them to WebP under public/parts/ and writes the runtime
 * catalog to src/dragon-parts.js.
 *
 *   node tools/render-parts.mjs [--only layer]
 */
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ALL_PARTS, renderSvg, LAYERS } from './art/index.mjs';

const only = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1] : null;
const parts = only ? ALL_PARTS.filter((p) => p.layer === only) : ALL_PARTS;

const tmp = path.resolve('build/parts-png');
fs.mkdirSync(tmp, { recursive: true });

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 512, height: 512 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));

const t0 = Date.now();
for (const part of parts) {
  const svg = renderSvg(part);
  const file = path.join(tmp, `${part.layer}__${part.id}.png`);
  await page.setContent(
    `<!doctype html><html><body style="margin:0;background:transparent;overflow:hidden">` +
      `<div style="width:512px;height:512px">${svg}</div></body></html>`,
    { waitUntil: 'load' }
  );
  await page.screenshot({ path: file, omitBackground: true, clip: { x: 0, y: 0, width: 512, height: 512 } });
}
await browser.close();
console.log(`rendered ${parts.length} parts in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
if (errors.length) console.log('page errors:', errors.slice(0, 5));

// tiny PNG sanity check: every file must be non-empty
for (const f of fs.readdirSync(tmp)) {
  const st = fs.statSync(path.join(tmp, f));
  if (st.size < 600) console.log('SUSPICIOUS (tiny)', f, st.size);
}

// WebP optimisation
execFileSync('python3', ['tools/optimize-parts.py'], { stdio: 'inherit' });

// runtime catalog
const catalog = LAYERS.map((layer) => ({
  id: layer.id,
  ko: layer.ko,
  parts: layer.parts.map((p) => ({
    id: p.id,
    name: p.name,
    element: p.element,
    rarity: p.rarity,
    img: `parts/${layer.id}/${p.id}.webp`,
    thumb: `parts/thumb/${layer.id}/${p.id}.webp`,
  })),
}));

const out = `// AUTO-GENERATED by tools/render-parts.mjs — do not edit by hand.
export const DRAGON_LAYERS = ${JSON.stringify(catalog, null, 2)};

export const LAYER_KO = ${JSON.stringify(Object.fromEntries(LAYERS.map((l) => [l.id, l.ko])), null, 2)};

export const PART_BY_ID = Object.fromEntries(
  DRAGON_LAYERS.flatMap((l) => l.parts.map((p) => [\`\${l.id}:\${p.id}\`, p]))
);
`;
fs.writeFileSync('src/dragon-parts.js', out);
const bytes = LAYERS.flatMap((l) => l.parts).reduce(
  (s, p) => s + fs.statSync(path.join('public/parts', p.layer, `${p.id}.webp`)).size,
  0
);
console.log(
  `catalog: ${LAYERS.map((l) => `${l.id} ${l.parts.length}`).join(', ')} · total ${(bytes / 1024).toFixed(0)}KB`
);
